function cleanMoney(value, currency) {
  let text = value.replace(/[^\d.,-]/g, "");
  if (currency === "USD") return text.replace(/,/g, "");
  return text.replace(/\./g, "");
}

function formatMoneyInput(value, currency, canonical = false) {
  const decimalSeparator = currency === "USD" ? "." : ",";
  const groupingSeparator = currency === "USD" ? "," : ".";
  let cleaned = value.replace(/[^\d.,-]/g, "");
  if (canonical && currency === "IDR") {
    cleaned = cleaned.replace(".", ",");
    if (cleaned.endsWith(",00")) cleaned = cleaned.slice(0, -3);
  }
  const decimalPosition = cleaned.indexOf(decimalSeparator);
  const hasDecimal = decimalPosition >= 0;
  let integer = hasDecimal ? cleaned.slice(0, decimalPosition) : cleaned;
  let fraction = hasDecimal ? cleaned.slice(decimalPosition + 1).replace(/[^\d]/g, "").slice(0, 2) : "";
  integer = integer.replace(/[^\d]/g, "").replace(/\B(?=(\d{3})+(?!\d))/g, groupingSeparator);
  return integer + (hasDecimal ? decimalSeparator + fraction : "");
}

function formatMoneyField(input) {
  const currency = document.body.dataset.currency === "USD" ? "USD" : "IDR";
  const start = input.selectionStart || 0;
  const digitCount = input.value.slice(0, start).replace(/[^\d]/g, "").length;
  input.value = formatMoneyInput(input.value, currency);
  let position = 0;
  let seenDigits = 0;
  while (position < input.value.length && seenDigits < digitCount) {
    if (/\d/.test(input.value[position])) seenDigits += 1;
    position += 1;
  }
  input.setSelectionRange(position, position);
}

document.querySelectorAll("[data-money-input]").forEach((input) => {
  const wrapper = document.createElement("span");
  wrapper.className = "money-input-wrap";
  const prefix = document.createElement("span");
  prefix.className = "money-prefix";
  prefix.textContent = document.body.dataset.currency === "USD" ? "$" : "Rp.";
  input.parentNode.insertBefore(wrapper, input);
  wrapper.append(prefix, input);
  input.value = formatMoneyInput(input.value, document.body.dataset.currency, true);
  input.addEventListener("input", () => formatMoneyField(input));
});

document.addEventListener("submit", (event) => {
  const currency = document.body.dataset.currency === "USD" ? "USD" : "IDR";
  event.target.querySelectorAll("[data-money-input]").forEach((input) => {
    input.value = cleanMoney(input.value, currency);
  });
  const message = event.target.dataset.confirm;
  if (message && !window.confirm(message)) event.preventDefault();
});

