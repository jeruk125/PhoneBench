const languageKey = "phonebench-language";
const originalText = new WeakMap();
const originalTitle = document.title;

function translateText(text) {
  if (translations[text]) return translations[text];
  const dynamicMessages = [
    [/^Repair ticket (.+) created\.$/, "Tiket perbaikan $1 dibuat."],
    [/^Attempt #(\d+) recorded\.$/, "Upaya #$1 dicatat."],
    [/^Draft invoice (.+) created\.$/, "Draf faktur $1 dibuat."],
    [/^Backup created: (.+)$/, "Cadangan dibuat: $1"],
    [/^Backup failed: (.+)$/, "Pembuatan cadangan gagal: $1"],
    [/^Restore failed: (.+)$/, "Pemulihan gagal: $1"],
    [/^Attachment restore failed: (.+)$/, "Pemulihan lampiran gagal: $1"],
    [/^WhatsApp send failed: (.+)$/, "Pengiriman WhatsApp gagal: $1"],
  ];
  for (const [pattern, translation] of dynamicMessages) {
    const match = text.match(pattern);
    if (match) return translation.replace("$1", match[1]);
  }
  return text;
}

function setLanguage(language) {
  const isIndonesian = language === "id";
  document.documentElement.lang = isIndonesian ? "id" : "en";
  document.title = isIndonesian ? (translations[originalTitle] || originalTitle) : originalTitle;

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node);
    const original = source.trim();
    if (original) node.nodeValue = source.replace(original, isIndonesian ? translateText(original) : original);
  }

  document.querySelectorAll("[placeholder], [aria-label]").forEach((element) => {
    for (const attribute of ["placeholder", "aria-label"]) {
      const value = element.getAttribute(attribute);
      if (!value) continue;
      if (isIndonesian) {
        if (translations[value]) element.dataset[`original${attribute}`] = value;
        if (translations[value]) element.setAttribute(attribute, translations[value]);
      } else {
        const original = element.dataset[`original${attribute}`];
        if (original) element.setAttribute(attribute, original);
      }
    }
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === language));
  });
}

document.addEventListener("click", (event) => {
  const languageButton = event.target.closest("[data-language]");
  if (languageButton) {
    const language = languageButton.dataset.language;
    localStorage.setItem(languageKey, language);
    setLanguage(language);
    return;
  }
  const button = event.target.closest("[data-copy]");
  if (!button) return;
  const input = document.querySelector(button.dataset.copy);
  if (!input) return;
  input.select();
  navigator.clipboard.writeText(input.value).then(() => {
    button.textContent = localStorage.getItem(languageKey) === "id" ? translations.Copied : "Copied";
  });
});

